setTimeout(() => {
  let passed = 0;
  try {
    const D=debugGame, {S,E,G,SH}=D;
    const assert=(v,msg)=>{if(!v)throw Error(msg); passed++;};
    S.settings.tutorialDone=true; S.settings.hints=false;
    document.querySelector('[data-act="play"]').click();
    S.settings.tut={home:true,sell:false}; D.flush();
    document.querySelector('.app').style.width='320px';
    document.querySelector('[data-act="nav"][data-group="kho"]').click(); D.flush();
    document.querySelector('.tile[data-tab="thucung"]').click(); D.flush();
    const tabs=document.querySelector('.pet-tabs'), chips=[...tabs.children];
    assert(chips.length===3 && tabs.textContent.includes('Chó Shiba'), 'Three correctly named pets');
    assert(getComputedStyle(tabs).flexWrap==='nowrap' && getComputedStyle(tabs).overflowX==='auto', 'Pet tabs horizontally scroll');
    assert(chips.every(c=>Math.abs(c.getBoundingClientRect().top-chips[0].getBoundingClientRect().top)<1), 'Pet tabs on one line');
    S.money=1e9; E.adoptPet('shiba'); D.flush();
    assert(document.querySelector('.pet-tabs'), 'Pet tabs remain after adoption');
    document.querySelector('[data-act="petsel"][data-k="meo"]').click(); D.flush();
    assert(document.querySelector('[data-act="adopt"][data-k="meo"]'), 'Other pet preview remains selectable');
    D.unlockAll(); D.fillStock(100); S.staff={}; S.equip.mayPhat=2; S.equip.giayPhep=1;
    assert(!G.startShift(), 'Shift starts'); S.settings.tut.sell=true; D.flush();
    SH.ev.bo=[]; SH.ev.ins=[];
    document.querySelector('.upgrade-shortcut').click();
    assert(document.querySelector('.upgrade-item[data-id="mayPhat"]') && document.querySelector('.upgrade-item[data-id="giayPhep"]'), 'Purchased equipment visible in list');
    document.querySelector('#modal .modal-back:last-child [data-modal-x]').click();
    G.pickCup('M'); G.startPour('traSua'); SH.board.fill=.4;
    D.events.blackout(20);
    assert(document.querySelector('[data-act="yes"]') && SH.ev.mode==='full' && !SH.board.pouring, 'Outage waits for consent');
    document.querySelector('[data-act="yes"]').click(); D.counterFrame();
    assert(SH.ev.mode==='gen2' && !G.startPour('traSua'), 'Large generator powers dispenser');
    document.querySelector('.upgrade-shortcut').click(); document.querySelector('.upgrade-item[data-id="mayPhat"]').click();
    assert(document.querySelector('#modal .modal-back:last-child').textContent.includes('Đang cấp điện'), 'Running generator status');
    document.querySelector('#modal .modal-back:last-child [data-modal-x]').click(); document.querySelector('#modal .modal-back:last-child [data-modal-x]').click();
    const before=SH.board.fill; G.updateShift(.2); assert(SH.board.fill>before, 'Powered pour advances');
    G.stopPour(); SH.board.fill=.95; G.sealCup(); G.updateShift(2);
    assert(SH.board.phase==='ready', 'Powered sealing finishes'); G.trashCup();
    G.updateShift(25); S.equip.mayPhat=1; D.events.blackout(20);
    document.querySelector('[data-act="yes"]').click();
    G.pickCup('M'); assert(G.startPour('traSua') && SH.ev.mode==='gen1', 'Mini generator matches tier duties');
    SH.board.tea='traSua'; SH.board.fill=.95; G.sealCup(); G.updateShift(2);
    assert(SH.board.phase==='ready', 'Mini generator powers sealer'); G.trashCup();
    G.updateShift(25); S.equip.mayPhat=2; D.events.blackout(20);
    document.querySelector('[data-act="no"]').click();
    G.pickCup('M'); assert(G.startPour('traSua') && SH.ev.mode==='full', 'Decline keeps outage blocking');
    S.staff.genZ={shifts:0}; const used=JSON.stringify(S.lastUsed); G.updateShift(.2);
    assert(!SH.jobs.length && JSON.stringify(S.lastUsed)===used, 'Staff cannot bypass unpowered machines');
    S.staff={}; G.trashCup(); G.updateShift(25);
    const cash=S.money; D.events.licenseCheck(); G.updateShift(.01);
    assert(document.querySelector('[data-act="go"]').textContent.includes('Xuất trình') && S.money===cash, 'License needs explicit presentation');
    document.querySelector('[data-act="go"]').click();
    assert(S.money>cash && document.querySelector('.ev-verdict.ok') && !SH.ev.halt, 'Purchased license passes after consent');
    document.querySelector('[data-act="ok"]').click(); S.equip.giayPhep=0;
    D.events.licenseCheck(); G.updateShift(.01);
    assert(document.querySelector('[data-act="go"]').textContent.includes('chưa có'), 'Missing license clearly described');
    document.querySelector('[data-act="go"]').click();
    assert(SH.ev.halt>0 && document.querySelector('.ev-verdict.bad'), 'Missing license imposes penalty');
    document.querySelector('[data-act="ok"]').click();
    document.body.dataset.docFixesPassed=String(passed);
  } catch(e) { document.body.dataset.docFixesError=e.message; console.error(e); }
},500);
